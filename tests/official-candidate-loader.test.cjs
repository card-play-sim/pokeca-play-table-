const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ctx={window:{}};
vm.runInNewContext(fs.readFileSync('ui/official-candidate-loader.js','utf8'),ctx);
const load=ctx.window.PokecaOfficialCandidates.normalize;
const card={officialCardId:'47847',name:'メガガルーラex',verificationStatus:'verified',cardType:'pokemon',pokemonStage:'たね',hp:300,attacks:[{name:'マシンガンコンボ',cost:['無色'],text:'効果'}],abilities:[{name:'おつかいダッシュ',text:'効果'}],cardNumber:'M1S 051/063',regulationMark:'I',officialPageUrl:'https://www.pokemon-card.com/card-search/details.php/card/47847/regu/XY',imageSourceUrl:'https://www.pokemon-card.com/assets/images/card_images/large/M1S/047847_P_MGARURAEX.jpg'};
const fixture={status:'CANDIDATES_ONLY_NOT_ENGINE_READY',adoptedPrintIds:[],candidateCount:1,cards:[card]};
const loaded=load(fixture);
assert.equal(loaded.count,1);
assert.equal(loaded.byId['47847'].hp,300);
assert.equal(loaded.byName['メガガルーラex'].length,1);
assert.equal(loaded.imageByOfficialCardId['47847'].name,'メガガルーラex');
assert.equal(loaded.status,'CANDIDATES_ONLY');
assert.throws(()=>load({...fixture,adoptedPrintIds:['47847']}));
assert.throws(()=>load({...fixture,candidateCount:2}));
assert.throws(()=>load({...fixture,cards:[card,card],candidateCount:2}));
assert.throws(()=>load({...fixture,cards:[{...card,hp:0}]}));
assert.throws(()=>load({...fixture,cards:[{...card,verificationStatus:'unverified'}]}));
assert.throws(()=>load({...fixture,cards:[{...card,officialPageUrl:'https://example.com/47847'}]}));
assert.throws(()=>load({...fixture,cards:[{...card,imageSourceUrl:'https://example.com/47847.jpg'}]}));
assert.throws(()=>load({...fixture,cards:[{...card,regulationMark:'G'}]}));
console.log('Official candidate loader tests passed');
