'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const mobile=fs.readFileSync(path.join(root,'ui/mobile.js'),'utf8');
const registry=fs.readFileSync(path.join(root,'ui/verified-card-art.js'),'utf8');
const context={window:{PokecaArt:{'架空たね':'data:image/png;base64,example'}}};
vm.runInNewContext(registry,context);
const start=mobile.indexOf('function imageURL(card){');
const end=mobile.indexOf('  function fallbackArt(',start);
assert(start>=0 && end>start,'imageURL function exists');
const resolve=vm.runInNewContext('('+mobile.slice(start,end).trim()+')',context);
const official={name:'メガガルーラex',officialCardId:'47847'};
assert.match(resolve(official),/^https:\/\/www\.pokemon-card\.com\//);
assert.equal(resolve({...official,name:'別カード'}),'','ID/name mismatch must not show unrelated image');
assert.equal(resolve({name:'架空たね'}),'data:image/png;base64,example','legacy synthetic art remains');
assert.equal(resolve({name:'架空たね',officialCardId:'99999'}),'','unknown official ID must not fall back by name');
assert.equal(resolve({name:'架空たね',evolutionCards:[{name:'架空進化'}]}),'','evolved print without art must not show basic art');
assert.equal(resolve({name:'架空たね',evolutionCards:[{name:'メガガルーラex',officialCardId:'47847'}]}),resolve(official),'evolved print with verified ID uses evolved art');
assert.equal(resolve({name:'架空たね',imageUrl:'http://insecure.invalid/x.jpg'}),'','reject non-HTTPS explicit URL');
assert(mobile.includes("img.nextElementSibling.hidden=false"),'image failure fallback handler remains');
const index=fs.readFileSync(path.join(root,'index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
assert(index.includes('ui/verified-card-art.js?build=189'));
assert(sw.includes('ui/verified-card-art.js?build=189'));
assert(mobile.includes("画像診断を一括保存（JSON）"),'fixed deck bulk diagnostics export exists');
assert(mobile.includes("pokeca-image-diagnostics.json"),'fixed deck bulk diagnostics download filename exists');
assert(mobile.includes("window.PokecaImageFailures"),'real image load failures are recorded');
assert(mobile.includes("missingPreviewNames"),'missing preview names included in diagnostic export');
assert(mobile.includes("unresolvedEngineNames"),'unresolved engine records included in diagnostic export');
console.log('PASS: card image resolution, evolution, safety and PWA asset wiring');
