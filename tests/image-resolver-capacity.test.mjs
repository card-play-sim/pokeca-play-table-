import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context={window:{},fetch:async()=>({ok:true,json:async()=>({cards:[]})})};
vm.runInNewContext(fs.readFileSync('ui/official-image-validation.js','utf8'),context);
vm.runInNewContext(fs.readFileSync('ui/card-image-resolver.js','utf8'),context);
const resolver=context.window.PokecaImageResolver;
const prefix='https://www.pokemon-card.com/assets/images/card_images/large/TEST/';
const records=Object.fromEntries(Array.from({length:5001},(_,i)=>[String(60000+i),{name:'検証'+i,sourceUrl:prefix+(60000+i)+'.jpg'}]));
assert.equal(resolver.register(records),5001);
assert.equal(resolver.count(),5001);
assert.equal(resolver.resolve({officialCardId:'60000',name:'検証0'}),prefix+'60000.jpg');
assert.equal(resolver.resolve({officialCardId:'60000',name:'別名'}),'');
assert.equal(resolver.resolvePreview({name:'検証0'}),prefix+'60000.jpg');
assert.equal(resolver.resolvePreview({officialCardId:'99999',name:'検証0'}),'');
assert.equal(resolver.register({'70000':{name:'検証0',sourceUrl:prefix+'70000.jpg'}}),1);
assert.equal(resolver.resolvePreview({name:'検証0'}),'','multiple prints must be ambiguous');
assert.equal(resolver.resolve({officialCardId:'70000',name:'検証0'}),prefix+'70000.jpg');
assert.throws(()=>resolver.register({'80000':{name:'new',sourceUrl:prefix+'80000.jpg'},'60000':{name:'wrong',sourceUrl:prefix+'60000.jpg'}}),/IMAGE_REGISTRY_CONFLICT/);
assert.equal(resolver.count(),5002,'collision must not partially mutate registry');
console.log('PASS: 5001 indexed resolver entries, strict print identity, ambiguous preview, atomic conflict');
