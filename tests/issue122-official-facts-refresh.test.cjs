'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),crypto=require('node:crypto');
const {parse}=require('../scripts/parse-official-pokemon-energy.cjs');
const {refresh,chooseVerifiedPair}=require('../scripts/refresh-uncompiled-official-facts.cjs');
const id='45944',path='data/effect-extensions/evidence/'+id+'.json',proof=JSON.parse(fs.readFileSync(path));
const p=parse(proof.html);
const name=(proof.html.match(/<h1[^>]*>(.*?)<\/h1>/s)?.[1]||'').replace(/<[^>]*>/g,'').replace(/&nbsp;/g,' ').replace(/&amp;/g,'&').trim();
let image=proof.html.match(/<img[^>]*src="([^"]*\/card_images\/large\/[^"]+)"/)[1];
if(image.startsWith('/'))image='https://www.pokemon-card.com'+image;
const row={...p,officialCardId:id,officialPageUrl:proof.url,name,deckName:name,imageSourceUrl:image,deckPrintAdopted:false,source:{path,sha256:proof.htmlSha256,textSha256:crypto.createHash('sha256').update(p.text).digest('hex')}};
const stale={...row,facts:{...row.facts,hp:row.facts.hp+10}};
const call=(records,protectedRows=[],source=proof)=>refresh({checkpoint:{records},intake:{records:records.slice()},compiled:{records:protectedRows},proofFor:()=>source});
const fixed=call([stale]);assert.equal(fixed.changes.length,1);assert.deepEqual(fixed.checkpoint.records,[row]);assert.deepEqual(fixed.intake.records,[row]);assert.deepEqual(stale.facts.hp,row.facts.hp+10);
assert.equal(call([stale],[row]).changes.length,0);
assert.equal(call([row]).changes.length,0);
const tampered={...stale,attacks:stale.attacks.map((a,i)=>i===0?{...a,text:a.text+'山札を引く。'}:a)};
assert.equal(call([tampered]).changes.length,0);
assert.equal(call([stale],[],{...proof,html:proof.html+'tamper'}).changes.length,0);
assert.deepEqual(chooseVerifiedPair(stale,row,proof),row);
assert.throws(()=>chooseVerifiedPair(stale,tampered,proof),/NON_FACT_RECORD_CONFLICT/);
assert.throws(()=>chooseVerifiedPair(stale,{...stale,facts:{...stale.facts,hp:1}},proof),/NEITHER_RECORD_MATCHES_OFFICIAL_FACTS/);
console.log('OFFICIAL_FACT_REFRESH PASS: exact immutable proof, protected compiled prints, strict non-fact conflicts');
